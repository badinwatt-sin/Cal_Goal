def clean(n):
    for a,b in PRE: n=n.replace(a,b)
    n=re.sub(r'(?<!ทู)น่า','น้ำ',n)            # OCR: น่า -> น้ำ (ยกเว้น ทูน่า)
    n=re.sub(r'(?<!ห)น้า(?!ม)','น้ำ',n)
    n=re.sub(r'([่-๋])\1',r'\1',n)              # วรรณยุกต์ซ้ำ
    n=n.strip(" ,'\"")
    n=re.sub(r',\s*้$','',n); n=re.sub(r',+',',',n).rstrip(',.')
    n=re.sub(r'\s*,\s*',', ',n)
    return n

