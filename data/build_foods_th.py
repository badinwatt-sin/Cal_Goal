UNIT={'piece':'ชิ้น','cup':'ถ้วย','pack':'ห่อ'}
def serving(r):
    b=r['energy_basis']
    if b=='per_100_g_edible_portion': return '100 ก.',100
    if b=='source_bottle_portion_not_100g':
        m=re.search(r'\((\d+)\s*oz\)',r['serving_description']); return f"1 แก้ว ({m.group(1)} ออนซ์)",None
    if b=='manufacturer_label_serving':
        s=r['serving_description'].replace('กรัม','ก.'); return s,float(r['serving_amount'])
    m=re.match(r'(\d+)\s+(piece|cup|pack)\s*\((\d+)\s*g\)',r['serving_description'])
    if m: return f"{m.group(1)} {UNIT[m.group(2)]} ({m.group(3)} ก.)",float(m.group(3))
    return r['serving_description'],None

